<?php

// Writes a GitHub contents API listing as a font manifest PHP array (file name => url, size, git blob SHA-1), so the
// plugin includes it from opcache instead of decoding the JSON.
// Usage: php tools/release/php-payload.php fonts/core-fonts.json fonts/core-fonts.php

if ( $argc !== 3 ) {
	fwrite( STDERR, "usage: php {$argv[0]} <listing.json> <manifest.php>\n" );
	exit( 1 );
}

$entries = json_decode( (string) file_get_contents( $argv[1] ), true );
if ( ! is_array( $entries ) ) {
	fwrite( STDERR, "FAIL: {$argv[1]} isn't a JSON list\n" );
	exit( 1 );
}

$lines = [
	'<?php',
	'',
	'// Generated by tools/release/php-payload.php from ' . $argv[1] . '. Do not edit.',
	'',
	"defined( 'ABSPATH' ) || exit;",
	'',
	'return [',
];

foreach ( $entries as $entry ) {
	$lines[] = sprintf(
		"\t%s => [ 'url' => %s, 'size' => %d, 'sha' => %s ],",
		var_export( (string) $entry['name'], true ),
		var_export( (string) $entry['download_url'], true ),
		(int) $entry['size'],
		var_export( (string) $entry['sha'], true )
	);
}

$lines[] = '];';

file_put_contents( $argv[2], implode( "\n", $lines ) . "\n" );
printf( "Wrote %d entries to %s\n", count( $entries ), $argv[2] );
